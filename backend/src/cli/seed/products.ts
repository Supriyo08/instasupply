function product(
  storeId: string,
  sku: string,
  name: string,
  categoryId: CategoryId,
  unit: SellUnit,
  priceCents: number,
  stockOnHand: number,
  weightKg: number,
  [l, w, h]: [number, number, number],
  imageKey: string | null,
  description: string,
  extras: Extras = {},
): SeedProduct {
  const dimsCm: DimsCm = { l, w, h };
  return {
    storeId,
    sku,
    name,
    brand: null,
    categoryId,
    familyKey: extras.familyKey ?? null,
    unit,
    size: extras.size ?? null,
    description,
    priceCents,
    compareAtCents: extras.compareAtCents ?? null,
    stockOnHand,
    maxPerOrder: null,
    weightKg,
    dimsCm,
    shipEstimated: false,
    active: true,
    featured: FEATURED.has(sku),
    badge: BADGES[sku] ?? null,
    imageKey,
    imagePath: null,
  };
}

