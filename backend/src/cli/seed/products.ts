/** The id of a seed product: `${storeId}--${skuSlug}` (MARKETPLACE §1.1). */
export const seedProductId = (item: Pick<SeedProduct, 'storeId' | 'sku'>): string =>
  productIdFor(item.storeId, item.sku);

/** A product by SKU; throws for an unknown one (a typo in a data file). */
export function seedProduct(sku: string): SeedProduct {
  const item = SEED_PRODUCTS.find((candidate) => candidate.sku === sku);
  if (!item) throw new Error(`unknown seed product ${sku}`);
  return item;
}
