#!/usr/bin/env node
/**
 * Compiles svg/*.svg into src/generated.ts (typed SVG strings) and preview/index.html (a contact
 * sheet for visual review). Run after adding or editing artwork: npm --workspace @instasupply/art run build
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const svgDir = path.join(root, 'svg');
const files = readdirSync(svgDir).filter((file) => file.endsWith('.svg')).sort();
const entries = files.map((file) => {
  const key = file.replace(/\.svg$/, '');
  const svg = readFileSync(path.join(svgDir, file), 'utf8').replace(/\s*\n\s*/g, ' ').trim();
  return { key, svg };
});

const lines = [
  '// Generated by scripts/build.mjs from svg/*.svg — do not edit by hand.',
  '/* eslint-disable */',
  `export const ART_KEYS = [${entries.map((entry) => `'${entry.key}'`).join(', ')}] as const;`,
  '',
  'export type ArtKey = (typeof ART_KEYS)[number];',
  '',
  'export const ART: Record<ArtKey, string> = {',
  ...entries.map((entry) => `  '${entry.key}': ${JSON.stringify(entry.svg)},`),
  '};',
  '',
];
writeFileSync(path.join(root, 'src', 'generated.ts'), lines.join('\n'));

const cards = entries
  .map(
    (entry) =>
      `<figure><div class="art">${entry.svg}</div><figcaption>${entry.key}</figcaption></figure>`,
  )
  .join('\n');
mkdirSync(path.join(root, 'preview'), { recursive: true });
writeFileSync(
  path.join(root, 'preview', 'index.html'),
  `<!doctype html><html><head><meta charset="utf-8"><title>InstaSupply art</title><style>
body{font-family:system-ui;background:#F4F5F9;margin:24px}main{display:grid;grid-template-columns:repeat(auto-fill,minmax(150px,1fr));gap:14px}
figure{margin:0;background:#fff;border-radius:10px;padding:10px;text-align:center}.art svg{width:100%;height:130px}
figcaption{font-size:12px;color:#868889;margin-top:6px}</style></head><body><h1>InstaSupply illustrations (${entries.length})</h1><main>${cards}</main></body></html>`,
);
console.log(`Built ${entries.length} illustrations → src/generated.ts, preview/index.html`);
